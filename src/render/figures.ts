export type OverlayMode = "over" | "under";

export interface Overlay {
  /** Which figures it fits. */
  readonly on: readonly Archetype[];
  /** "under" only paints empty pixels (wings, tails behind the body). */
  readonly mode: OverlayMode;
  /** `_` erases a pixel, `.` leaves it untouched. */
  readonly rows: readonly string[];
}

const BLANK = "................................";
const pad = (rows: readonly string[], top: number): string[] => [
  ...Array.from({ length: top }, () => BLANK),
  ...rows,
  ...Array.from({ length: Math.max(0, 32 - top - rows.length) }, () => BLANK),
];

